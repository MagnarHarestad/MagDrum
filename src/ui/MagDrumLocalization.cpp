void initialiseMagDrumLocalization()
{
    auto language=juce::SystemStats::getDisplayLanguage().trim().toLowerCase();
    if(language.isEmpty())language=juce::SystemStats::getUserLanguage().trim().toLowerCase();
    if(language.startsWith("sv"))
        juce::LocalisedStrings::setCurrentMappings(new juce::LocalisedStrings(swedishTranslations,true));
    else
        juce::LocalisedStrings::setCurrentMappings(nullptr);
}
